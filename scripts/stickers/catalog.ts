/**
 * src/lib/stickers/catalog.generated.ts from the files themselves: every sticker's animation and key frame and every pack
 * icon in public/stickers, read back (frames, one play's length, bytes, content version). Then public/stickers/catalog.json
 * (catalog-json.ts) and the review page's data (designs/stickers/review/data.js).
 *
 *   npx tsx scripts/stickers/catalog.ts          (render.ts runs it after every render)
 *
 * A file that doesn't move (a placeholder still) is `frames: 1, durationMs: 0`. Each sticker also carries where its
 * drawing sits in its square (`box`: every frame of the animation together; `poseBox`: the key frame, its thumb) — see
 * `inkBox`.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import sharp from 'sharp';
import { STICKER_PACKS } from '../../src/lib/stickers/catalog';
import { contentVersion, readWebp } from './pipeline';

export const ROOT = resolve(__dirname, '../..');
export const PUBLIC = join(ROOT, 'public/stickers');
export const GENERATED = join(ROOT, 'src/lib/stickers/catalog.generated.ts');
export const REVIEW = join(ROOT, 'designs/stickers/review');
/** Each drawn sticker's hero time, seconds (render.ts records it): the frame its thumb is. */
export const HEROES = join(REVIEW, 'heroes.json');

export function readHeroes(): Record<string, number> {
  return existsSync(HEROES) ? (JSON.parse(readFileSync(HEROES, 'utf8')) as Record<string, number>) : {};
}

/** Where a drawing sits in its square: [left, top, right, bottom], fractions of the side (3 decimals). */
export type InkBox = [number, number, number, number];

export interface ArtEntry {
  durationMs: number;
  frames: number;
  bytes: number;
  v: string;
  /** A sticker's drawn area, every frame of its animation together (never a pack icon). */
  box?: InkBox;
  /** Its key frame's (the thumb's) drawn area. */
  poseBox?: InkBox;
}

/**
 * Where a sticker's drawing sits in its square (round 24, the owner: 點點 stands low in its square, so a sent sticker
 * and its quote carried a band of empty paper above it): the union of every frame's pixels with alpha above 8 of 255,
 * as fractions [left, top, right, bottom] of the side. The thread trims the empty paper above and below by the
 * animation's box (no frame ever leaves it, so nothing is cut), a quote centres the thumb's.
 */
export async function inkBox(file: string): Promise<InkBox> {
  const img = sharp(file, { pages: -1 });
  const meta = await img.metadata();
  const { data, info } = await img.ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const w = info.width;
  const pageH = meta.pageHeight ?? info.height;
  const pages = Math.round(info.height / pageH);
  let l = w, t = pageH, r = -1, b = -1;
  for (let p = 0; p < pages; p++) {
    for (let y = 0; y < pageH; y++) {
      const row = (p * pageH + y) * w * 4;
      for (let x = 0; x < w; x++) {
        if (data[row + x * 4 + 3] <= 8) continue;
        if (x < l) l = x;
        if (x > r) r = x;
        if (y < t) t = y;
        if (y > b) b = y;
      }
    }
  }
  if (r < 0) return [0, 0, 1, 1];
  const f = (v: number, n: number) => Math.round((v / n) * 1000) / 1000;
  return [f(l, w), f(t, pageH), f(r + 1, w), f(b + 1, pageH)];
}

/** What the files in public/stickers say, keyed `<pack>/<id>` and `<pack>/icon`, in the picker's order. */
export async function readArt(): Promise<Record<string, ArtEntry>> {
  const art: Record<string, ArtEntry> = {};
  for (const p of STICKER_PACKS) {
    const icon = join(PUBLIC, p.id, 'icon.webp');
    if (existsSync(icon)) {
      const b = readFileSync(icon);
      art[`${p.id}/icon`] = { durationMs: 0, frames: 1, bytes: b.length, v: contentVersion([b]) };
    }
    for (const st of p.stickers) {
      const anim = join(PUBLIC, p.id, `${st.id}.webp`);
      const thumb = join(PUBLIC, p.id, `${st.id}.thumb.webp`);
      if (!existsSync(anim) || !existsSync(thumb)) continue;
      const a = readFileSync(anim);
      const info = readWebp(a);
      art[`${p.id}/${st.id}`] = {
        durationMs: info.animated ? info.durationMs : 0, frames: info.frames, bytes: a.length, v: contentVersion([a, readFileSync(thumb)]),
        box: await inkBox(anim), poseBox: await inkBox(thumb),
      };
    }
  }
  return art;
}

export function generatedSource(art: Record<string, ArtEntry>): string {
  const boxes = (a: ArtEntry) => (a.box && a.poseBox ? `, box: ${JSON.stringify(a.box)}, poseBox: ${JSON.stringify(a.poseBox)}` : '');
  const rows = Object.entries(art).map(([key, a]) =>
    `  ${JSON.stringify(key)}: { durationMs: ${a.durationMs}, frames: ${a.frames}, bytes: ${a.bytes}, v: ${JSON.stringify(a.v)}${boxes(a)} },`);
  return `// Generated by the sticker pipeline (scripts/stickers: npm run stickers) — do not edit by hand.
// Each sticker's animation as public/stickers/<pack>/<id>.webp holds it (one play's length, its frames, its bytes) and
// the content version of it and its key frame; each pack's icon. A still (a placeholder not yet drawn) is 1 frame, 0 ms.
// A sticker's \`box\` is where its drawing sits in its square over every frame, \`poseBox\` its key frame's: [left, top,
// right, bottom], fractions of the side.

export interface StickerArt {
  durationMs: number;
  frames: number;
  bytes: number;
  v: string;
  box?: readonly [number, number, number, number];
  poseBox?: readonly [number, number, number, number];
}

export const STICKER_ART: Readonly<Record<string, StickerArt>> = {
${rows.join('\n')}
};
`;
}

/** The review page's list: names, numbers and sizes, so the static page needs no directory listing. */
export function reviewData(art: Record<string, ArtEntry>): string {
  const heroes = readHeroes();
  const packs = STICKER_PACKS.map(p => ({
    id: p.id, hero: p.hero, name: p.name,
    icon: art[`${p.id}/icon`] ?? null,
    stickers: p.stickers.map(st => {
      const a = art[`${p.id}/${st.id}`];
      const thumb = join(PUBLIC, p.id, `${st.id}.thumb.webp`);
      return { id: st.id, name: st.name, ...(a ?? {}), hero: heroes[`${p.id}/${st.id}`] ?? null, thumbBytes: existsSync(thumb) ? statSync(thumb).size : 0 };
    }),
  }));
  return `// Generated by scripts/stickers/catalog.ts — the review page's list of stickers.\nwindow.STICKERS = ${JSON.stringify(packs, null, 1)};\n`;
}

export async function writeCatalog(): Promise<Record<string, ArtEntry>> {
  const art = await readArt();
  writeFileSync(GENERATED, generatedSource(art));
  // catalog-json reads catalog.generated.ts at import: a fresh process sees the file just written
  execFileSync('npx', ['tsx', join(ROOT, 'scripts/stickers/catalog-json.ts')], { stdio: 'inherit', cwd: ROOT });
  mkdirSync(REVIEW, { recursive: true });
  writeFileSync(join(REVIEW, 'data.js'), reviewData(art));
  return art;
}

if (require.main === module) {
  void writeCatalog().then((art) => console.log(`catalog: ${Object.keys(art).length} entries`));
}
