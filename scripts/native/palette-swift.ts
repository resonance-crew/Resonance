/**
 * The palette (src/lib/design/palette.ts) → Swift: every token of every
 * theme in both schemes, as Display P3 tables the iOS app resolves at draw
 * time (DesignSystem `Palette`: a UIColor provider reading the trait
 * collection's interface style and the theme trait), the oklch() each was
 * made from (what native/fixtures/palette.json pins, for the app's tests),
 * the roles made from a card's hue (HUE_ROLES) and the scheme's numbers.
 *
 * `Tokens.<colour>` (Generated/Tokens.swift, scripts/native/tokens.ts) are
 * these dynamic colours, so every call site recolours by itself.
 *
 *   npx tsx scripts/native/tokens.ts      (writes both files)
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import {
  ACCENTS,
  CARD_FAMILY_COUNT,
  HUE_ROLES,
  PALETTE_TOKENS,
  SCHEMES,
  SCHEME_NUMBERS,
  cssOklch,
  paletteFor,
  type PaletteToken,
} from '../../src/lib/design/palette';
import { encode, linearSrgbToLinearP3, srgbHex, toLinearSrgb } from './oklch';

const r4 = (n: number) => Math.round(n * 10000) / 10000;
const camel = (s: string) => s.replace(/^color-/, '').replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());

/** A token's Swift name: camelCase without `color-`, keeping the names the app had (a family's deep pen is `cardBorder0Dark`). */
export function swiftName(token: PaletteToken): string {
  const deep = /^card-border-deep-(\d)$/.exec(token);
  if (deep) return `cardBorder${deep[1]}Dark`;
  return camel(token);
}

const HUE_ROLE_NAMES = Object.keys(HUE_ROLES) as (keyof typeof HUE_ROLES)[];

/** The members of `enum Tokens` that are colours: one dynamic colour per token, and the families as arrays. */
export function swiftTokenColours(): string {
  const light = paletteFor('terracotta', 'light');
  const dark = paletteFor('terracotta', 'dark');
  const lines = PALETTE_TOKENS.map(
    (t) =>
      `    /// --${t} · terracotta: light ${srgbHex(light[t])}, dark ${srgbHex(dark[t])}\n` +
      `    public static let ${swiftName(t)} = Color(uiColor: UI.${swiftName(t)})`,
  );
  const family = (prefix: string, name: (i: number) => string) =>
    `    public static let ${prefix}: [Color] = [${Array.from({ length: CARD_FAMILY_COUNT }, (_, i) => name(i)).join(', ')}]`;
  return [
    '    // The palette (src/lib/design/palette.ts, scripts/native/palette-swift.ts): every colour follows the',
    "    // interface style and the theme (`AccentTrait`) wherever it is drawn — a SwiftUI view, a UIKit view's",
    '    // dynamic colour, an attributed string. `Tokens.UI.<colour>` is the same colour as a UIColor.',
    ...lines,
    '',
    family('cardFills', (i) => `cardFill${i}`),
    family('cardBorders', (i) => `cardBorder${i}`),
    family('cardBordersDeep', (i) => `cardBorder${i}Dark`),
    family('cardInteriors', (i) => `cardInterior${i}`),
    family('cardSeparators', (i) => `cardSeparator${i}`),
    family('cardNoteInks', (i) => `cardNoteInk${i}`),
    family('cardStripes', (i) => `cardStripe${i}`),
    family('cardAccents', (i) => `cardAccent${i}`),
    family('cardHovers', (i) => `cardHover${i}`),
    family('cardSkeletons', (i) => `cardSkeleton${i}`),
    family('cardTags', (i) => `cardTag${i}`),
    family('cardPills', (i) => `cardPill${i}`),
    family('cardPillInks', (i) => `cardPillInk${i}`),
  ].join('\n');
}

/** `Tokens.UI`: the palette's colours as dynamic UIColors (UIKit views, attributed strings, layers via `resolvedColor`). */
export function swiftUITokens(): string {
  return `
extension Tokens {
    /// The palette's colours for UIKit: dynamic, resolved by whatever trait collection draws them.
    public nonisolated enum UI {
${PALETTE_TOKENS.map((t) => `        public static let ${swiftName(t)} = Palette.uiColor(.${swiftName(t)})`).join('\n')}
    }
}
`;
}

function paletteSwift(): string {
  const tables = ACCENTS.flatMap((a) => SCHEMES.map((s) => paletteFor(a, s)));
  const p3 = tables.flatMap((p) =>
    PALETTE_TOKENS.map((t) => {
      const [r, g, b] = linearSrgbToLinearP3(toLinearSrgb(p[t])).map(encode).map(r4);
      return `${r}, ${g}, ${b}, ${r4(p[t].alpha)}`;
    }),
  );
  const oklch = tables.flatMap((p) => PALETTE_TOKENS.map((t) => `"${cssOklch(p[t])}"`));
  const hueRows = HUE_ROLE_NAMES.map((r) => {
    const { light, dark } = HUE_ROLES[r];
    return `        ${light[0]}, ${light[1]}, ${dark[0]}, ${dark[1]},`;
  });
  return `// Generated by scripts/native/palette-swift.ts from src/lib/design/palette.ts — do not edit.
import Foundation

/// The themes (palette.ts ACCENTS), in its order; the raw value is what Settings stores.
public nonisolated enum Accent: String, CaseIterable, Sendable {
${ACCENTS.map((a) => `    case ${a}`).join('\n')}
}

/// The two schemes (palette.ts SCHEMES), in its order.
public nonisolated enum PaletteScheme: String, CaseIterable, Sendable {
${SCHEMES.map((s) => `    case ${s}`).join('\n')}
}

/// Every palette colour (palette.ts PALETTE_TOKENS), in its order.
public nonisolated enum PaletteToken: Int, CaseIterable, Sendable {
${PALETTE_TOKENS.map((t) => `    case ${swiftName(t)}`).join('\n')}

    /// The palette's own name (\`color-cream\`): the web's custom property, palette.json's key.
    public var paletteName: String { PaletteTables.names[rawValue] }
}

/// The colours made from a card's hue (palette.ts HUE_ROLES, the web's \`--hue-*\`), in its order.
public nonisolated enum HueRole: Int, CaseIterable, Sendable {
${HUE_ROLE_NAMES.map((r) => `    case ${camel(r)}`).join('\n')}

    /// The palette's own name (\`pen-deep\`).
    public var paletteName: String { PaletteTables.hueNames[rawValue] }
}

nonisolated enum PaletteTables {
    static let names: [String] = [
${PALETTE_TOKENS.map((t) => `        "${t}",`).join('\n')}
    ]

    static let hueNames: [String] = [
${HUE_ROLE_NAMES.map((r) => `        "${r}",`).join('\n')}
    ]

    /// Display P3 red, green, blue and alpha of every token: theme by theme (Accent order), light
    /// then dark, tokens in PaletteToken order — \`((accent * 2 + scheme) * tokens + token) * 4\`.
    static let p3: [Float] = [
${p3.map((v) => `        ${v},`).join('\n')}
    ]

    /// What each entry of \`p3\` was made from, as palette.json writes it (same order).
    static let oklch: [String] = [
${oklch.map((v) => `        ${v},`).join('\n')}
    ]

    /// Each HueRole's light L, C, then dark L, C.
    static let hueRoles: [Double] = [
${hueRows.join('\n')}
    ]

    /// SCHEME_NUMBERS: how strong the grain is drawn, light then dark.
    static let grainScale: [Double] = [${SCHEMES.map((s) => SCHEME_NUMBERS[s]['grain-scale']).join(', ')}]
    /// SCHEME_NUMBERS: how strong the thought map's dotted paper is inked, light then dark.
    static let mapDotAlpha: [Double] = [${SCHEMES.map((s) => SCHEME_NUMBERS[s]['map-dot-alpha']).join(', ')}]
    /// SCHEME_NUMBERS: the reading progress line's glow, light then dark.
    static let readingProgressGlowAlpha: [Double] = [${SCHEMES.map((s) => SCHEME_NUMBERS[s]['reading-progress-glow-alpha']).join(', ')}]
}
`;
}

/** Writes Generated/PaletteTables.swift (the tables) and the launch assets; Tokens.swift takes `swiftTokenColours` and `swiftUITokens`. */
export function writePaletteSwift(root: string): void {
  writeLaunchAssets(root);
  const p = resolve(root, 'apps/ios/Packages/DesignSystem/Sources/DesignSystem/Generated/PaletteTables.swift');
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, paletteSwift());
}

/**
 * The launch screen's paper and mark in both appearances (the system draws it in its own, before the
 * app can lay Settings → 外觀 on its scene): Assets.xcassets LaunchBackground (the paper) and
 * LaunchMark (the icon's waves in the accent), light and dark terracotta.
 */
export function writeLaunchAssets(root: string): void {
  const assets = resolve(root, 'apps/ios/Resonance/Resources/Assets.xcassets');
  const light = paletteFor('terracotta', 'light');
  const dark = paletteFor('terracotta', 'dark');
  const components = (hex: string) =>
    `{ "alpha" : "1.000", "red" : "0x${hex.slice(1, 3).toUpperCase()}", "green" : "0x${hex.slice(3, 5).toUpperCase()}", "blue" : "0x${hex.slice(5, 7).toUpperCase()}" }`;
  writeFileSync(
    resolve(assets, 'LaunchBackground.colorset/Contents.json'),
    `{
  "colors" : [
    { "color" : { "color-space" : "srgb", "components" : ${components(srgbHex(light['color-cream']))} }, "idiom" : "universal" },
    { "appearances" : [ { "appearance" : "luminosity", "value" : "dark" } ], "color" : { "color-space" : "srgb", "components" : ${components(srgbHex(dark['color-cream']))} }, "idiom" : "universal" }
  ],
  "info" : { "author" : "xcode", "version" : 1 }
}
`,
  );
  const mark = resolve(assets, 'LaunchMark.imageset');
  const svg = readFileSync(resolve(mark, 'LaunchMark.svg'), 'utf8');
  writeFileSync(resolve(mark, 'LaunchMark.svg'), svg.replace(/stroke="#[0-9a-f]{6}"/, `stroke="${srgbHex(light['color-terracotta'])}"`));
  writeFileSync(
    resolve(mark, 'LaunchMark-dark.svg'),
    svg
      .replace(/stroke="#[0-9a-f]{6}"/, `stroke="${srgbHex(dark['color-terracotta'])}"`)
      .replace(/<!--[\s\S]*?-->/, '<!-- LaunchMark.svg in the dark accent, for a dark system (scripts/native/palette-swift.ts writes it). -->'),
  );
  writeFileSync(
    resolve(mark, 'Contents.json'),
    `{
  "images" : [
    { "filename" : "LaunchMark.svg", "idiom" : "universal" },
    { "appearances" : [ { "appearance" : "luminosity", "value" : "dark" } ], "filename" : "LaunchMark-dark.svg", "idiom" : "universal" }
  ],
  "info" : { "author" : "xcode", "version" : 1 }
}
`,
  );
}
