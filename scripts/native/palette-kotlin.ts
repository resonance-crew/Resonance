/**
 * The palette (src/lib/design/palette.ts) → Kotlin, for scripts/native/tokens.ts:
 *
 *  • generated/Palette.kt — `ResonanceColors`, every palette token for one
 *    theme in one scheme, the four themes × two schemes as tables of OKLCH
 *    numbers (Display P3 is worked out on the device, by the same maths the
 *    wallpaper's palette takes: `PaletteFormula`), and `LocalResonanceColors`;
 *  • generated/Tokens.kt — each colour a `@Composable @ReadOnlyComposable`
 *    getter of `LocalResonanceColors.current`, so every screen recolours with
 *    the scheme and theme `ResonanceTheme` provides, and a read outside
 *    composition (a draw lambda, a cache, a top-level value) is a compile
 *    error rather than a colour left light; lengths stay plain constants.
 *
 * Names: the token without `color-`, in PascalCase (`color-cream` → Cream,
 * `card-border-deep-3` → CardBorderDeep3), as the apps always called them.
 */
import { ACCENTS, PALETTE_TOKENS, SCHEMES, SCHEME_NUMBERS, paletteFor, type PaletteToken } from '../../src/lib/design/palette';

const pascal = (s: string) => s.replace(/^color-/, '').replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase());
const upperSnake = (s: string) => s.replace(/-/g, '_').toUpperCase();
const num = (n: number) => {
  const r = Math.round(n * 1e6) / 1e6;
  return Number.isInteger(r) ? `${r}.0` : `${r}`;
};

/** The family tokens, without their index (card-fill-0 … card-fill-5 → card-fill). */
const FAMILY_PREFIXES = [...new Set(PALETTE_TOKENS.filter((t) => /-\d+$/.test(t)).map((t) => t.replace(/-\d+$/, '')))];

/** What each token is for, where a name alone doesn't say. */
const ROLES: Partial<Record<PaletteToken, string>> = {
  'color-cream': 'the paper',
  'color-cream-dark': 'the recessed well (bands, tracks, skeletons): darker than the paper in both schemes',
  'color-card-bg': 'a raised card: lighter than the paper in both schemes',
  'color-terracotta': 'the accent, whatever its hue',
  'color-terracotta-light': "the accent's wash",
  'color-text': 'the ink',
  'color-text-muted': 'the quiet ink',
  'button-fill': "a solid button's face; its label is the paper",
  'toward-ink': '"further from the paper": black in light, white in dark (a press or hover wash, at a low alpha)',
  'shadow-ink': 'a real drop shadow',
  'grain-ink': "the grain's specks: dark on cream, light on night paper",
  'picture-backing': "behind a story picture: none in light, a light paper in dark (a transparent logo's black words still show)",
  scrim: 'what a modal lays over the screen',
};

export function kotlinPalette(): string {
  const accentName = (a: string) => pascal(a);
  const tables = ACCENTS.flatMap((a) =>
    SCHEMES.map((s) => {
      const p = paletteFor(a, s);
      const rows = PALETTE_TOKENS.map((t) => `        ${num(p[t].L)}, ${num(p[t].C)}, ${num(p[t].H)}, ${num(p[t].alpha)}, // ${t}`);
      return `    /** ${a}, ${s}. */\n    val ${upperSnake(a)}_${s.toUpperCase()}: DoubleArray get() = doubleArrayOf(\n${rows.join('\n')}\n    )`;
    }),
  );
  const props = PALETTE_TOKENS.map((t, i) => `    /** --${t}${ROLES[t] ? ` — ${ROLES[t]}` : ''} */\n    val ${pascal(t)}: Color = at(${i})`);
  const lists = FAMILY_PREFIXES.map(
    (f) => `    /** --${f}-0…5, in CardPalette.HUES order. */\n    val ${pascal(f)}s: List<Color> = listOf(${[0, 1, 2, 3, 4, 5].map((i) => `${pascal(`${f}-${i}`)}`).join(', ')})`,
  );
  const numbers = Object.keys(SCHEME_NUMBERS.light).map(
    (k) => `    /** --${k} */\n    val ${pascal(k)}: Float = if (dark) ${num(SCHEME_NUMBERS.dark[k as keyof (typeof SCHEME_NUMBERS)['dark']])}f else ${num(SCHEME_NUMBERS.light[k as keyof (typeof SCHEME_NUMBERS)['light']])}f`,
  );
  return `// Generated by scripts/native/palette-kotlin.ts from src/lib/design/palette.ts — do not edit.
package com.resonance.design.generated

import androidx.compose.runtime.Immutable
import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.graphics.Color
import com.resonance.design.OklchColor

/** The four themes (palette.ts ACCENTS), each with its light and dark table. [key] is its stored name. */
enum class PaletteTheme(val key: String) {
${ACCENTS.map((a) => `    ${accentName(a)}("${a}"),`).join('\n')}
}

/**
 * Every colour one theme wears in one scheme: palette.ts's tokens (PALETTE_TOKENS), drawn in
 * Display P3 from their OKLCH numbers ([oklch], L 0…1, C, H, alpha per token in [TOKENS] order).
 * The four themes' tables are [of]; the wallpaper's (Android 12+) is built at run time by
 * PaletteFormula from the same recipes. Tokens keep their role, not their lightness: [Cream] is the
 * paper and [Text] the ink in both schemes. Screens read these through [Tokens] (the
 * [LocalResonanceColors] ResonanceTheme provides); an image that leaves the device reads
 * [LightTerracotta] instead.
 */
@Immutable
class ResonanceColors(
    /** Drawn for the dark scheme. */
    val dark: Boolean,
    oklch: DoubleArray,
) {
    init {
        require(oklch.size == TOKENS.size * 4) { "\${oklch.size / 4} colours for \${TOKENS.size} tokens" }
    }

    /** Each token's OKLCH: L (0…1), C, H (degrees), alpha, [TOKENS] order. */
    val oklch: DoubleArray = oklch.copyOf()

    private fun at(i: Int): Color = OklchColor.of(this.oklch[4 * i], this.oklch[4 * i + 1], this.oklch[4 * i + 2], this.oklch[4 * i + 3])

${props.join('\n')}

${lists.join('\n')}

${numbers.join('\n')}

    /** A token's OKLCH (L 0…1, C, H, alpha) by its palette.ts name. */
    fun oklchOf(token: String): DoubleArray {
        val i = TOKENS.indexOf(token)
        require(i >= 0) { "no palette token \$token" }
        return oklch.copyOfRange(4 * i, 4 * i + 4)
    }

    private val hash = 31 * this.oklch.contentHashCode() + dark.hashCode()

    override fun equals(other: Any?): Boolean = other === this || (other is ResonanceColors && other.hash == hash && other.dark == dark && other.oklch.contentEquals(oklch))
    override fun hashCode(): Int = hash
    override fun toString(): String = "ResonanceColors(\${if (dark) "dark" else "light"}, cream=\${oklch.take(3)}, accent=\${oklch.drop(12).take(3)})"

    companion object {
        /** palette.ts's token names, in the order [oklch] holds them. */
        val TOKENS: List<String> = listOf(
${PALETTE_TOKENS.map((t) => `            "${t}",`).join('\n')}
        )

        private val built = arrayOfNulls<ResonanceColors>(PaletteTheme.entries.size * 2)

        /** A theme's palette in a scheme (each built once). */
        fun of(theme: PaletteTheme, dark: Boolean): ResonanceColors {
            val i = theme.ordinal * 2 + if (dark) 1 else 0
            built[i]?.let { return it }
            val table = when (theme) {
${ACCENTS.map((a) => `                PaletteTheme.${accentName(a)} -> if (dark) PaletteTables.${upperSnake(a)}_DARK else PaletteTables.${upperSnake(a)}_LIGHT`).join('\n')}
            }
            return ResonanceColors(dark, table).also { built[i] = it }
        }

        /** Light terracotta: every screen's default, and what an image leaving the device is drawn in (the 9:16 card, an avatar's backing). */
        val LightTerracotta: ResonanceColors get() = of(PaletteTheme.Terracotta, false)
    }
}

/** The palette every [Tokens] colour reads; ResonanceTheme provides it (light terracotta outside one). */
val LocalResonanceColors = staticCompositionLocalOf { ResonanceColors.LightTerracotta }

/** palette.ts's tables, as OKLCH numbers (L 0…1, C, H, alpha per token, ResonanceColors.TOKENS order). */
internal object PaletteTables {
${tables.join('\n\n')}
}
`;
}

/** Tokens.kt: the palette's colours as composable getters, then the lengths as they always were. */
export function kotlinTokens(header: string, pens: { ink: number; inkLight: number; inkStrong: number }, lengths: { name: string; value: number; source: string }[]): string {
  const getter = (name: string, type: string, doc: string) =>
    `    /** ${doc} */\n    val ${name}: ${type}\n        @Composable @ReadOnlyComposable get() = LocalResonanceColors.current.${name}`;
  const colours = PALETTE_TOKENS.map((t) => getter(pascal(t), 'Color', `--${t}${ROLES[t] ? ` — ${ROLES[t]}` : ''}`));
  const lists = FAMILY_PREFIXES.map((f) => getter(`${pascal(f)}s`, 'List<Color>', `--${f}-0…5, in CardPalette.HUES order.`));
  const numbers = Object.keys(SCHEME_NUMBERS.light).map((k) => getter(pascal(k), 'Float', `--${k}`));
  return `// ${header}
package com.resonance.design.generated

import androidx.compose.runtime.Composable
import androidx.compose.runtime.ReadOnlyComposable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.unit.dp

/**
 * The design tokens. Colours follow the scheme and theme on screen (ResonanceTheme provides
 * [LocalResonanceColors]); read them in composition and hand them to a draw block as values. A
 * picture that leaves the device reads ResonanceColors.LightTerracotta instead.
 */
object Tokens {
${colours.join('\n')}

${lists.join('\n')}

${numbers.join('\n')}

    /** One pen for the whole app (src/lib/design/strokes.ts). */
    val Ink = ${pens.ink}.dp
    val InkLight = ${pens.inkLight}.dp
    val InkStrong = ${pens.inkStrong}.dp
${lengths.map((l) => `\n    /** ${l.source} */\n    const val ${l.name[0].toUpperCase()}${l.name.slice(1)} = ${l.value}f`).join('')}
}
`;
}
