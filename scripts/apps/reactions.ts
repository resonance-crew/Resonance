/**
 * The five message reactions (src/lib/design/reactions.ts) → data for the
 * native apps: each glyph's layers as flat command lists (0 x y = move,
 * 1 x y = line, 2 x1 y1 x2 y2 x y = curve, 3 = close — the icons' format),
 * their offsets baked in, and the sticker colours as Display P3 components
 * (fixed in both schemes, as emoji are). The apps draw them with their own
 * ReactionGlyph view.
 *
 *   npx tsx scripts/apps/reactions.ts          (part of `npm run apps:generate`)
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { REACTION_COLOURS, REACTION_GLYPHS, REACTION_IDS, placedPath, type ReactionColour } from '../../src/lib/design/reactions';
import { encode, linearSrgbToLinearP3, parseOklch, toLinearSrgb } from '../native/oklch';

const root = resolve(__dirname, '../..');

function commands(d: string, where: string): number[] {
  const out: number[] = [];
  const tokens = d.match(/[A-Za-z]|-?\d*\.?\d+(?:e-?\d+)?/g) ?? [];
  const arity: Record<string, [number, number]> = { M: [0, 2], L: [1, 2], C: [2, 6], Z: [3, 0] };
  let i = 0;
  let op = '';
  while (i < tokens.length) {
    if (/[A-Za-z]/.test(tokens[i])) op = tokens[i++];
    const spec = arity[op];
    if (!spec) throw new Error(`${where}: path command "${op}" — the apps draw only absolute M/L/C/Z`);
    const args = tokens.slice(i, i + spec[1]).map(Number);
    if (args.length !== spec[1] || args.some(Number.isNaN)) throw new Error(`${where}: bad arguments for ${op}`);
    out.push(spec[0], ...args);
    i += spec[1];
    if (op === 'M') op = 'L';
    if (op === 'Z') op = '';
  }
  return out;
}

const r4 = (n: number) => Math.round(n * 10000) / 10000;
const p3 = (colour: ReactionColour) =>
  linearSrgbToLinearP3(toLinearSrgb(parseOklch(REACTION_COLOURS[colour]))).map(encode).map(r4) as [number, number, number];
const colours = Object.keys(REACTION_COLOURS) as ReactionColour[];
const num = (n: number) => `${n}`;

const header = 'Generated by scripts/apps/reactions.ts from src/lib/design/reactions.ts — do not edit.';

const swift = `// ${header}
// Commands: 0 x y = move, 1 x y = line, 2 x1 y1 x2 y2 x y = curve, 3 = close (a 24 box).

/// The sticker colours, the same in both schemes (Display P3).
public enum ReactionColour: Sendable {
${colours.map((c) => `    case ${c}`).join('\n')}

    public var p3: (red: Double, green: Double, blue: Double) {
        switch self {
${colours.map((c) => `        case .${c}: (${p3(c).map(num).join(', ')})`).join('\n')}
        }
    }
}

public struct ReactionLayer: Sendable {
    public let commands: [Double]
    public let fill: ReactionColour?
    public let stroke: ReactionColour?
    /// The pen, in the 24 box.
    public let width: Double
    public let opacity: Double
}

/// A message's reactions, by the ids the server stores.
public enum ReactionId: String, CaseIterable, Sendable {
${REACTION_IDS.map((id) => `    case ${id}`).join('\n')}

    /// The glyph's layers, bottom to top.
    public var layers: [ReactionLayer] {
        switch self {
${REACTION_IDS.map(
  (id) =>
    `        case .${id}: [\n` +
    REACTION_GLYPHS[id]
      .map(
        (l) =>
          `            ReactionLayer(commands: [${commands(placedPath(l), id).map(num).join(', ')}], fill: ${l.fill ? `.${l.fill}` : 'nil'}, stroke: ${l.stroke ? `.${l.stroke}` : 'nil'}, width: ${l.width ?? 0}, opacity: ${l.opacity ?? 1}),`,
      )
      .join('\n') +
    `\n        ]`,
).join('\n')}
        }
    }
}
`;

const pascal = (s: string) => s[0].toUpperCase() + s.slice(1);
const kotlin = `// ${header}
// Commands: 0 x y = move, 1 x y = line, 2 x1 y1 x2 y2 x y = curve, 3 = close (a 24 box).
package com.resonance.design.generated

/** The sticker colours, the same in both schemes (Display P3 components). */
enum class ReactionColour(val red: Float, val green: Float, val blue: Float) {
${colours.map((c) => `    ${pascal(c)}(${p3(c).map((n) => `${n}f`).join(', ')}),`).join('\n')}
}

class ReactionLayer(
    val commands: FloatArray,
    val fill: ReactionColour?,
    val stroke: ReactionColour?,
    /** The pen, in the 24 box. */
    val width: Float,
    val opacity: Float,
)

/** A message's reactions, by the ids the server stores (\`key\`). */
enum class ReactionId(val key: String) {
${REACTION_IDS.map((id) => `    ${pascal(id)}("${id}"),`).join('\n')}
    ;

    /** The glyph's layers, bottom to top. */
    val layers: List<ReactionLayer>
        get() = when (this) {
${REACTION_IDS.map(
  (id) =>
    `            ${pascal(id)} -> listOf(\n` +
    REACTION_GLYPHS[id]
      .map(
        (l) =>
          `                ReactionLayer(floatArrayOf(${commands(placedPath(l), id).map((n) => `${n}f`).join(', ')}), ${l.fill ? `ReactionColour.${pascal(l.fill)}` : 'null'}, ${l.stroke ? `ReactionColour.${pascal(l.stroke)}` : 'null'}, ${l.width ?? 0}f, ${l.opacity ?? 1}f),`,
      )
      .join('\n') +
    `\n            )`,
).join('\n')}
        }

    companion object {
        fun of(key: String?): ReactionId? = entries.firstOrNull { it.key == key }
    }
}
`;

const outputs: [string, string][] = [
  ['apps/ios/Packages/DesignSystem/Sources/DesignSystem/Generated/Reactions.swift', swift],
  ['apps/android/core/design/src/main/kotlin/com/resonance/design/generated/Reactions.kt', kotlin],
];
for (const [out, body] of outputs) {
  mkdirSync(dirname(resolve(root, out)), { recursive: true });
  writeFileSync(resolve(root, out), body);
}
console.log(`${REACTION_IDS.length} reactions → Swift + Kotlin`);
