// rig.svg: the character at rest, flat data-part groups in paint order (kit.md "Rig contract").
import { defs, parts, P, HEIGHT } from './dot.mjs';

export function rigSvg() {
  const attrs = p => [
    `data-part="${p.name}"`, `data-parent="${p.parent}"`, `data-pivot="${p.pivot[0]} ${p.pivot[1]}"`,
    p.len != null ? `data-len="${p.len}"` : '', p.angle != null ? `data-angle="${p.angle}"` : '',
    p.variantOf ? `data-variant-of="${p.variantOf}" display="none"` : '',
  ].filter(Boolean).join(' ');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 700 760" width="700" height="760">
<!-- 點點 Pip, round 3 of the 摺摺 series: rest pose in series units. Generated by gen/build.mjs; do not edit by hand. -->
${defs()}
<g data-rig data-name="點點 Pip" data-prefix="dt-" data-ground="${P.cx} ${P.ground}" data-face-center="${P.face[0]} ${P.face[1]}" data-height="${HEIGHT}" data-walk="hop">
${parts('dt-rig-').map(p => ` <g ${attrs(p)}>${p.svg}</g>`).join('\n')}
</g>
</svg>
`;
}
