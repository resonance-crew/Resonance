// rig.svg: 牽牽 standing at rest, flat data-part groups in paint order (kit.md "Rig contract").
import { defs, parts, G, HEIGHT } from './tag.mjs';

export function rigSvg() {
  const p = parts('tg-rig-');
  const sole = G.hipL[1] + G.legLen * Math.sin(G.legRest[0] * Math.PI / 180) + 18; // ankle + the sole's depth
  const len = Math.round(sole - G.hipL[1]);
  const part = (name, parent, pivot, extra = '') =>
    `<g data-part="${name}" data-parent="${parent}" data-pivot="${pivot.map(v => +v.toFixed(1)).join(' ')}"${extra}${/variant-of/.test(extra) ? ' style="display:none"' : ''}>${p[name]}</g>`;
  const body = [
    part('shadow', 'root', [G.cx, G.ground]),
    part('leg-l', 'root', G.hipL, ` data-len="${len}"`),
    part('leg-r', 'root', G.hipR, ` data-len="${len}"`),
    part('torso', 'body', G.torsoPivot),
    part('torso-alt', 'body', G.torsoPivot, ' data-variant-of="torso"'),
    part('deco', 'body', G.knot),
    part('cheeks', 'face', [G.cx, G.cheekL[1]]),
    part('eye-l', 'face', G.eyeL),
    part('eye-r', 'face', G.eyeR),
    part('eye-l-shut', 'face', G.eyeL, ' data-variant-of="eye-l"'),
    part('eye-r-shut', 'face', G.eyeR, ' data-variant-of="eye-r"'),
    part('mouth', 'face', G.mouth),
    part('mouth-o', 'face', G.mouth, ' data-variant-of="mouth"'),
    part('arm-l', 'body', G.bradL, ` data-angle="${G.armRest[0]}"`),
    part('arm-r', 'body', G.bradR, ` data-angle="${G.armRest[1]}"`),
  ].join('\n ');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 700 760" width="700" height="760">
<!-- 牽牽 Twine — the 摺摺 series, round 3. Generated by gen/build.mjs; edit the generator, not this file. -->
${defs()}
<g data-rig data-name="牽牽 Twine" data-prefix="tg-" data-ground="${G.cx} ${G.ground}" data-face-center="${G.faceCenter.join(' ')}" data-height="${HEIGHT}" data-walk="walk">
 ${body}
</g>
</svg>
`;
}
