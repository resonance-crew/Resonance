// build.mjs — 1. regenerates cast.js from whatever cast/<slug>/manifest.json exist (placeholders/<name>/parts fill in
// while fewer than two are there), adding what outline.py reads from the part images (the torso's pointer shape
// `hit`, torso-alt's `reveal` point) to each manifest; 2. writes stage.bundle.js, a classic-script copy of the ES modules (mascot-stage.js,
// cast.js, prototype.js) with ledges.json inlined, which index.html loads — browsers refuse ES modules from file://.
//   node build.mjs          (sync-cast.sh runs it; run it yourself after editing the engine, the prototype or ledges)
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const read = f => readFileSync(join(HERE, f), 'utf8');
const ORDER = ['tuck', 'tag', 'card', 'dot', 'night'];

// --- cast.js --------------------------------------------------------------------------------------------------------
const has = (...p) => existsSync(join(HERE, ...p));
const dirs = dir => (has(dir) ? readdirSync(join(HERE, dir), { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name) : []);
// the torso's outline (the engine's pointer shape) and where torso-alt differs (a corner a mitten can lift), written
// into the cast's own manifest too, so a page that fetches manifest.json gets them
function outline(dir) {
  const file = join(HERE, dir, 'manifest.json'), m = JSON.parse(readFileSync(file, 'utf8'));
  try {
    const o = JSON.parse(execFileSync('python3', [join(HERE, 'outline.py'), join(HERE, dir)]).toString());
    for (const p of m.parts) {
      if (p.name === 'torso') p.hit = o.hit;
      if (p.name === 'torso-alt') { if (o.reveal) p.reveal = o.reveal; else delete p.reveal; }
    }
    writeFileSync(file, JSON.stringify(m, null, 1));
  } catch (e) { console.warn(`${dir}: no outline (${e.message.split('\n')[0]})`); }
  return m;
}
const drawn = dirs('cast').filter(slug => has('cast', slug, 'manifest.json')).sort((a, b) => (ORDER.indexOf(a) + 1 || 99) - (ORDER.indexOf(b) + 1 || 99))
  .map(slug => ({ slug, base: `cast/${slug}/`, manifest: outline(`cast/${slug}`) }));
const stand = dirs('placeholders').filter(slug => has('placeholders', slug, 'parts', 'manifest.json')).map(slug => ({ slug, base: `placeholders/${slug}/parts/`, manifest: JSON.parse(read(`placeholders/${slug}/parts/manifest.json`)) }));
const cast = drawn.length >= 2 ? drawn : [...drawn, ...stand];
const slim = m => ({ ...m, parts: m.parts.map(({ hidden, ...p }) => p) });
writeFileSync(join(HERE, 'cast.js'), `// cast.js — generated by build.mjs (sync-cast.sh): who the prototype puts on stage, with their manifests inlined.
// ${drawn.length ? `drawn: ${drawn.map(c => c.slug).join(', ')}` : 'no drawn characters yet'}${cast.length > drawn.length ? '; placeholders fill in' : ''}.
export const CAST = ${JSON.stringify(cast.map(c => ({ slug: c.slug, base: c.base, manifest: slim(c.manifest) })))};
`);

// --- stage.bundle.js ------------------------------------------------------------------------------------------------
function asBlock(file) {   // a module's body in its own scope, handing its exports to the bundle's scope
  const src = read(file);
  const names = [...src.matchAll(/^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)].map(m => m[1]);
  const body = src.replace(/^import\s[^;]*;\s*$/gm, '').replace(/^export\s+/gm, '');
  if (/\bimport\.meta\b|^\s*import\s*\(/m.test(body)) throw new Error(`${file}: no import.meta or dynamic import in bundled modules`);
  return `// ---- ${file}\nconst { ${names.join(', ')} } = (() => {\n${body}\nreturn { ${names.join(', ')} };\n})();\n`;
}
const bundle = `// stage.bundle.js — generated by build.mjs from mascot-stage.js, cast.js, prototype.js and ledges.json. Do not edit.
(() => {
${asBlock('mascot-stage.js')}
${asBlock('cast.js')}
const LEDGES = ${JSON.stringify(JSON.parse(read('ledges.json')))};
${asBlock('prototype.js')}
window.MascotStage = { createStage, loadCast, mountPrototype, CAST, LEDGES };
})();
`;
writeFileSync(join(HERE, 'stage.bundle.js'), bundle);
console.log(`cast.js: ${cast.map(c => c.slug).join(', ')} · stage.bundle.js ${(bundle.length / 1024).toFixed(0)} KB`);
