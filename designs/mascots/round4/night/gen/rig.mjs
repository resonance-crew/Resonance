// The rig (kit.md "Rig contract") and the posed figure for the sheet, both from the parts in hush.mjs.
import { G, BRADS, decoPlace, defs, shadowSvg, legSvg, torsoSvg, starsSvg, starsGlowSvg, decoSvg, cheeksSvg, eyeSvg, mouthSvg, armSvg } from './hush.mjs';

const f = n => (Math.round(n * 10) / 10).toString();
const TORSO_PIVOT = [G.cx, G.hipY];
const DECO_PIVOT = decoPlace().clip;

export function rigSvg() {
  const I = 'nt-rig-';
  const part = (name, parent, pivot, inner, extra = '') =>
    ` <g data-part="${name}" data-parent="${parent}" data-pivot="${f(pivot[0])} ${f(pivot[1])}"${extra}>${inner}</g>\n`;
  const hide = ' display="none"';
  const [el, er] = G.eyes;
  const parts = [
    part('shadow', 'root', [G.cx, G.ground], shadowSvg()),
    part('leg-l', 'root', [G.hips[0], G.hipY], legSvg(I, 'l'), ` data-len="${G.ground - G.hipY}"`),
    part('leg-r', 'root', [G.hips[1], G.hipY], legSvg(I, 'r'), ` data-len="${G.ground - G.hipY}"`),
    // round 3 review: the arms paint behind the dome, their strips tucked under its torn edge (摺摺's way); the torso
    // shows the brad heads, and each arm keeps its own brad at its pivot, hidden until the stage brings it forward
    part('arm-l', 'body', BRADS.l, armSvg(I, 'l', G.rest.armL), ` data-angle="${G.rest.armL}"`),
    part('arm-r', 'body', BRADS.r, armSvg(I, 'r', G.rest.armR), ` data-angle="${G.rest.armR}"`),
    part('torso', 'body', TORSO_PIVOT, torsoSvg(I)),
    part('stars', 'body', [350, 380], starsSvg()),
    part('stars-glow', 'body', [350, 380], starsGlowSvg(), ` data-only="dark"${hide}`),
    part('deco', 'body', DECO_PIVOT, decoSvg()),
    part('cheeks', 'face', G.face, cheeksSvg()),
    part('eye-l', 'face', el, eyeSvg(I, 'l', 'open')),
    part('eye-r', 'face', er, eyeSvg(I, 'r', 'open')),
    part('eye-l-shut', 'face', el, eyeSvg(I, 'l', 'shut'), ` data-variant-of="eye-l"${hide}`),
    part('eye-r-shut', 'face', er, eyeSvg(I, 'r', 'shut'), ` data-variant-of="eye-r"${hide}`),
    part('eye-l-sleepy', 'face', el, eyeSvg(I, 'l', 'sleepy'), ` data-variant-of="eye-l"${hide}`),
    part('eye-r-sleepy', 'face', er, eyeSvg(I, 'r', 'sleepy'), ` data-variant-of="eye-r"${hide}`),
    part('eye-l-nap', 'face', el, eyeSvg(I, 'l', 'nap'), ` data-variant-of="eye-l"${hide}`),
    part('eye-r-nap', 'face', er, eyeSvg(I, 'r', 'nap'), ` data-variant-of="eye-r"${hide}`),
    part('mouth', 'face', G.mouth, mouthSvg('smile')),
    part('mouth-o', 'face', G.mouth, mouthSvg('o'), ` data-variant-of="mouth"${hide}`),
  ];
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 700 760" width="700" height="760">
<!-- 悄悄 Hush (round 3, the night member of the 摺摺 series). Generated by gen/build.mjs — edit the generator, not this file.
     Rig contract: kit.md. Parts are flat siblings in paint order (back to front). Variants and stars-glow start hidden.
     Arms are painted behind the torso (their strips tuck under the dome's edge); the torso carries the visible brad heads,
     and each arm also carries its own brad at its pivot (hidden under the sheet), so arm and brad stay one part. -->
${defs()}
<g data-rig data-name="悄悄 Hush" data-prefix="nt-" data-ground="${G.cx} ${G.ground}" data-face-center="${f(G.face[0])} ${f(G.face[1])}" data-height="${G.ground - G.top}" data-walk="walk">
${parts.join('')}</g>
</svg>
`;
}

// The same parts, posed the way the stage engine would move them (arms about the brads, legs about the hips, the
// body tilted and squashed about the torso pivot, the face slid, variants swapped). Arms are rebuilt at their pose
// angle so the glue shadow keeps falling down-right, as on the stage's baked images it turns with the arm. Arms sit
// behind the dome unless `front` (the stage's p.front: a mitten crossing the body — rubbing an eye, napping).
export function figure(I, o = {}) {
  const p = {
    armL: G.rest.armL, armR: G.rest.armR, legL: 0, legR: 0, tilt: 0, dy: 0, squash: 1, face: [0, 0], look: [0, 0],
    eyeL: 'open', eyeR: 'open', mouth: 'smile', glow: false, blush: 0.8, shadow: true, front: false, ...o,
  };
  const [px, py] = [G.cx, G.hipY];
  let bodyT = `translate(0 ${f(p.dy)}) rotate(${f(p.tilt)} ${px} ${py})`;
  if (p.squash !== 1) bodyT += ` translate(${px} ${py}) scale(1 ${p.squash}) translate(${-px} ${-py})`;
  const look = p.look;
  return `<g>
    ${p.shadow ? shadowSvg() : ''}
    ${legSvg(I, 'l', p.legL)}
    ${legSvg(I, 'r', p.legR)}
    <g transform="${bodyT}">
      ${p.front ? '' : armSvg(I, 'l', p.armL) + armSvg(I, 'r', p.armR)}
      ${torsoSvg(I)}
      ${starsSvg()}
      ${p.glow ? starsGlowSvg() : ''}
      ${decoSvg()}
      <g transform="translate(${f(p.face[0])} ${f(p.face[1])})">
        ${cheeksSvg(p.blush)}
        ${eyeSvg(I, 'l', p.eyeL, look)}
        ${eyeSvg(I, 'r', p.eyeR, look)}
        ${mouthSvg(p.mouth, look)}
      </g>
      ${p.front ? armSvg(I, 'l', p.armL) + armSvg(I, 'r', p.armR) : ''}
    </g>
  </g>`;
}
