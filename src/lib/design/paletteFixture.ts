/**
 * native/fixtures/palette.json: every theme's palette in both schemes, the
 * wallpaper formula at sampled system colours, and avatar fills — what the
 * apps' tests hold their generated tables (iOS, Android) and Android's
 * runtime formula (PaletteFormula, 桌布配色) to.
 */
import { ACCENTS, PALETTE_TOKENS, SCHEMES, avatarFill, cssOklch, paletteFor, paletteForHue, type Palette } from './palette';
import { AVATAR_COLORS } from './avatarColors';

const table = (p: Palette) => Object.fromEntries(PALETTE_TOKENS.map((t) => [t, cssOklch(p[t])]));

export const WALLPAPER_SAMPLES: readonly { hue: number; chroma: number }[] = [
  { hue: 25, chroma: 0.12 },
  { hue: 100, chroma: 0.09 },
  { hue: 160, chroma: 0.14 },
  { hue: 250, chroma: 0.11 },
  { hue: 310, chroma: 0.03 },
];

export function paletteFixture() {
  return {
    note: 'Generated by scripts/web/palette-css.ts from src/lib/design/palette.ts — do not edit. `accents`: each theme in both schemes (token → oklch(), alpha after a slash). `wallpaper`: paletteForHue(hue, chroma, scheme), the Android 12+ wallpaper colours, which the app computes at runtime. `avatars`: avatarFill(stored, scheme). Within 0.002 L / 0.002 C / 0.5° H counts as equal.',
    tokens: PALETTE_TOKENS,
    accents: Object.fromEntries(ACCENTS.map((a) => [a, Object.fromEntries(SCHEMES.map((s) => [s, table(paletteFor(a, s))]))])),
    wallpaper: WALLPAPER_SAMPLES.flatMap(({ hue, chroma }) => SCHEMES.map((scheme) => ({ hue, chroma, scheme, palette: table(paletteForHue(hue, chroma, scheme)) }))),
    avatars: AVATAR_COLORS.flatMap((stored) => SCHEMES.map((scheme) => ({ stored, scheme, fill: avatarFill(stored, scheme) }))),
  };
}
