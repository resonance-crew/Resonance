/**
 * The palette (./palette) as a stylesheet: what scripts/web/palette-css.ts
 * writes to src/styles/palette.css, and what the editor island's stylesheet
 * takes in hex (an older Android WebView reads no oklch()).
 *
 * `<html>` says which theme it wears with `data-accent` (absent: terracotta)
 * and, only when the reader chose one, `data-scheme` (absent: the system's,
 * through prefers-color-scheme). So:
 *   :root                                   light terracotta (and every scheme-only token)
 *   :root[data-accent=x]                    light x (only the tokens a theme changes)
 *   @media dark  :root:not([data-scheme=light])…   the dark tables, as the system asks
 *   :root[data-scheme=dark]…                the dark tables, as the reader chose
 * The accent rules carry one more attribute than the scheme rule they
 * follow, so a theme always wins over the scheme's terracotta defaults.
 */
import { srgbHex, toLinearSrgb, encode, type Oklch } from './oklch';
import {
  ACCENTS,
  DEFAULT_ACCENT,
  PALETTE_TOKENS,
  SCHEME_NUMBERS,
  cssOklch,
  paletteFor,
  type Accent,
  type Palette,
  type PaletteToken,
  type Scheme,
} from './palette';

export type PaletteCssFormat = 'oklch' | 'hex';

function value(c: Oklch, format: PaletteCssFormat): string {
  if (format === 'oklch') return cssOklch(c);
  if (c.alpha >= 1) return srgbHex(c);
  const [r, g, b] = toLinearSrgb(c).map((v) => Math.round(encode(v) * 255));
  return `rgb(${r} ${g} ${b} / ${Math.round(c.alpha * 1000) / 1000})`;
}

/** The tokens a theme's rule must set: those that differ from terracotta's in that scheme. */
function accentDelta(accent: Accent, scheme: Scheme): PaletteToken[] {
  const own = paletteFor(accent, scheme);
  const base = paletteFor(DEFAULT_ACCENT, scheme);
  return PALETTE_TOKENS.filter((t) => cssOklch(own[t]) !== cssOklch(base[t]));
}

function block(selector: string, palette: Palette, tokens: readonly PaletteToken[], format: PaletteCssFormat, extra: string[] = [], indent = ''): string {
  const lines = [...extra, ...tokens.map((t) => `--${t}: ${value(palette[t], format)};`)];
  return `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join('\n')}\n${indent}}`;
}

function schemeRules(scheme: Scheme, base: string, format: PaletteCssFormat, indent: string): string[] {
  const numbers = Object.entries(SCHEME_NUMBERS[scheme]).map(([k, v]) => `--${k}: ${v};`);
  const rules = [block(base, paletteFor(DEFAULT_ACCENT, scheme), PALETTE_TOKENS, format, [`color-scheme: ${scheme};`, ...numbers], indent)];
  for (const accent of ACCENTS) {
    if (accent === DEFAULT_ACCENT) continue;
    rules.push(block(`${base}[data-accent='${accent}']`, paletteFor(accent, scheme), accentDelta(accent, scheme), format, [], indent));
  }
  return rules;
}

/** The whole stylesheet. */
export function paletteCss(format: PaletteCssFormat = 'oklch'): string {
  const head = `/* Generated by scripts/web/palette-css.ts from src/lib/design/palette.ts — do not edit. */`;
  const light = schemeRules('light', ':root', format, '');
  const systemDark = schemeRules('dark', ":root:not([data-scheme='light'])", format, '  ');
  const chosenDark = schemeRules('dark', ":root[data-scheme='dark']", format, '');
  return [
    head,
    '',
    light.join('\n\n'),
    '',
    `@media (prefers-color-scheme: dark) {\n${systemDark.join('\n\n')}\n}`,
    '',
    chosenDark.join('\n\n'),
    '',
  ].join('\n');
}

/**
 * Light terracotta's `:root` alone — what a script or test that reads one
 * stylesheet's custom properties (the last of a name wins) takes as "the
 * tokens", beside tokens.css.
 */
export function lightRootCss(format: PaletteCssFormat = 'oklch'): string {
  return schemeRules('light', ':root', format, '')[0];
}
