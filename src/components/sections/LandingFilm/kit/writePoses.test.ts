/**
 * The film's writing poses are found ahead (kit/writePoses.generated.ts) so no frame waits on the search: this makes
 * each again and compares. After a change to the search, the slip, the pencil or a puppet's rig:
 *   UPDATE_WRITE_POSES=1 npx vitest run src/components/sections/LandingFilm/kit/writePoses.test.ts
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import { MASCOT_CAST } from '@/lib/mascots/cast.generated';
import { StickerPuppet, type Slug } from './puppet';
import { poseKey, searchWritePose, writePose, type FoundPose, type WriteOpts } from './write';
import { WRITE_POSES } from './writePoses.generated';
import type { ArmSide } from './puppet';

/** Every pose the film asks for (script/beats.ts): 摺摺 writing with either hand, 聆聆 with its larger card, 聆聆 reading card A in its left mitten, 牽牽's blank. */
const FILM_POSES: [Slug, ArmSide, ArmSide, WriteOpts][] = [
  ['tuck', 'R', 'L', {}],
  ['tuck', 'L', 'R', {}],
  ['card', 'R', 'L', { grow: 1.5 }],
  ['card', 'L', 'R', { penless: true, grow: 1.5 }],
  ['tag', 'R', 'L', { penless: true, grow: 1.3 }],
];
const ghost = (slug: Slug) => new StickerPuppet(null, null, { slug, k: 1 }, MASCOT_CAST.find((c) => c.slug === slug)!.manifest as never, '');
const round = (p: FoundPose): FoundPose => ({ hold: p.hold, scale: +p.scale.toFixed(5), rot: p.rot, anchor: p.anchor, pen: +p.pen.toFixed(5) });

describe('the writing poses found ahead', () => {
  const fresh = Object.fromEntries(FILM_POSES.map(([slug, hold, pen, opts]) => [poseKey(slug, hold, pen, opts.grow ?? 1, !!opts.penless), round(searchWritePose(ghost(slug), hold, pen, opts))]));

  it('are the ones the search finds today', () => {
    if (process.env.UPDATE_WRITE_POSES) {
      const file = fileURLToPath(new URL('./writePoses.generated.ts', import.meta.url));
      writeFileSync(
        file,
        `/** Generated by kit/writePoses.test.ts (UPDATE_WRITE_POSES=1): the film's own writing poses, found ahead. */\nimport type { FoundPose } from './write';\n\nexport const WRITE_POSES: Record<string, FoundPose> = ${JSON.stringify(fresh, null, 2)};\n`,
      );
      return;
    }
    expect(WRITE_POSES).toEqual(fresh);
  });

  it('serve the film without a search, the same pose the search would give', () => {
    if (process.env.UPDATE_WRITE_POSES) return;
    for (const [slug, hold, pen, opts] of FILM_POSES) {
      const wp = writePose(ghost(slug), hold, pen, opts);
      const found = fresh[poseKey(slug, hold, pen, opts.grow ?? 1, !!opts.penless)];
      expect(wp.scale).toBeCloseTo(found.scale, 4);
      expect(wp.rot).toBe(found.rot);
      expect(wp.anchor).toEqual(found.anchor);
    }
  });
});
